#!/usr/bin/env python3
# gen-font.py -- the BASIC screen's fonts (code page 437: 8 x 8, 8 x 14, 8 x 16) and the Latin-1 -> CP437 table,
# taken from Onyx's user/Libs/basic/basfont.h into turtle/font.js.
#   python3 tools/gen-font.py [path/to/Onyx]
# The glyphs: the VGA console fonts of Debian console-setup (u_vga16.bdf (c) 2000, 2001 Dmitry Bolkhovityanov,
# MIT licence; console fonts: public domain), as basfont.h says.
import base64, os, re, sys
here = os.path.dirname (os.path.abspath (__file__)); root = os.path.dirname (here)
onyx = sys.argv[1] if len (sys.argv) > 1 else os.path.join (os.path.dirname (root), 'Onyx')
src = open (os.path.join (onyx, 'user', 'Libs', 'basic', 'basfont.h'), encoding = 'utf-8').read ()
def table (name):
	body = src[src.index (name):]
	body = body[body.index ('{') + 1:body.index ('};')]
	body = re.sub (r'//[^\n]*', '', body)
	return [int (x, 0) for x in re.findall (r'0x[0-9A-Fa-f]+|\d+', body)]
f8, f14, f16, l1 = table ('basFont8['), table ('basFont14['), table ('basFont16['), table ('basLatin1To437[')
assert len (f8) == 2048 and len (f14) == 3584 and len (f16) == 4096 and len (l1) == 256
b = lambda a: base64.b64encode (bytes (a)).decode ()
with open (os.path.join (root, 'turtle', 'font.js'), 'w') as o:
	o.write ('// Generated by tools/gen-font.py from Onyx\'s basfont.h -- do not edit. Code page 437 in 8 x 8, 8 x 14, 8 x 16\n')
	o.write ('// (one byte a row, bit 7 the leftmost pixel); Latin-1 -> CP437. Glyphs: the VGA console fonts of Debian\n')
	o.write ('// console-setup (u_vga16.bdf (c) 2000, 2001 Dmitry Bolkhovityanov, MIT licence; console fonts: public domain).\n')
	o.write ('window.BASIC_FONT = { f8: "%s",\n f14: "%s",\n f16: "%s",\n latin1: %s };\n' % (b (f8), b (f14), b (f16), l1))
print ('turtle/font.js')
