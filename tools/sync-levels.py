#!/usr/bin/env python3
# sync-levels.py -- the level packs copied from Onyx (sdcard/apps/<game>.app/levels/) into turtle/levels.js and
# circuits/levels.js, and BASIC examples (sdcard/basic/examples) into turtle/onyx-examples.js (scripts, so the pages
# also work opened from the disk, without a server).
#   python3 tools/sync-levels.py [path/to/Onyx]      (default: ../Onyx beside this repository)
# MIT License -- Copyright (c) 2026 Stéphane Wegener and the Onyx contributors.
import json, os, sys

here = os.path.dirname (os.path.abspath (__file__))
root = os.path.dirname (here)
onyx = sys.argv[1] if len (sys.argv) > 1 else os.path.join (os.path.dirname (root), 'Onyx')
for game, ext, var in (('turtle', '.turtle', 'TURTLE_PACKS'), ('circuits', '.circuits', 'CIRCUITS_PACKS')):
	src = os.path.join (onyx, 'sdcard', 'apps', game + '.app', 'levels')
	packs = []
	for name in sorted (os.listdir (src)):
		if name.endswith (ext):
			with open (os.path.join (src, name), encoding = 'utf-8') as f: packs.append ({ 'name': name, 'text': f.read () })
	out = os.path.join (root, game, 'levels.js')
	with open (out, 'w', encoding = 'utf-8') as f:
		f.write ('// Generated by tools/sync-levels.py from Onyx\'s ' + game + '.app/levels -- do not edit by hand.\n')
		f.write ('window.' + var + ' = ' + json.dumps (packs, ensure_ascii = False, indent = 1) + ';\n')
	print (out, len (packs), 'packs')
# the free mode's examples from Onyx's BASIC (SD:/basic/examples): turtle/onyx-examples.js
ex = []
for name in ('hello.bas', 'guess.bas', 'graphics.bas', 'arkanoid.bas'):
	with open (os.path.join (onyx, 'sdcard', 'basic', 'examples', name), encoding = 'utf-8') as f: ex.append ({ 'name': name, 'text': f.read () })
for name in sorted (os.listdir (os.path.join (root, 'turtle', 'bas'))):	# (and Code is Fun's own, turtle/bas)
	if name.endswith ('.bas'):
		with open (os.path.join (root, 'turtle', 'bas', name), encoding = 'utf-8') as f: ex.append ({ 'name': name, 'text': f.read () })
out = os.path.join (root, 'turtle', 'onyx-examples.js')
with open (out, 'w', encoding = 'utf-8') as f:
	f.write ('// Generated by tools/sync-levels.py from Onyx\'s SD:/basic/examples and turtle/bas -- do not edit by hand.\n')
	f.write ('window.ONYX_EXAMPLES = ' + json.dumps (ex, ensure_ascii = False, indent = 1) + ';\n')
print (out, len (ex), 'examples')
